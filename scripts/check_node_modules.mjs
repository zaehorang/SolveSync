// 설치된 node_modules가 package-lock.json과 같은 버전인지 검사한다.
//
// `npm ls`는 package.json의 범위만 봐서 lock이 1.63인데 1.62.1이 깔려 있어도
// 통과한다. npm이 설치 때 남기는 node_modules/.package-lock.json과 비교해야
// 실제 일치를 알 수 있다. 다르면 `npm ci`가 필요하다.

import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const installedFile = resolve(root, "node_modules/.package-lock.json");

if (!existsSync(installedFile)) {
  console.error("node_modules가 없거나 설치 기록(.package-lock.json)이 없다. npm ci가 필요하다.");
  process.exit(1);
}

const locked = JSON.parse(readFileSync(resolve(root, "package-lock.json"), "utf8")).packages;
const installed = JSON.parse(readFileSync(installedFile, "utf8")).packages;
const mismatches = [];

for (const [path, entry] of Object.entries(locked)) {
  // 빈 문자열 key는 루트 package다. link와 다른 플랫폼용 optional 패키지는
  // 설치되지 않는 것이 정상이라 누락으로 보지 않는다.
  if (path === "" || entry.link === true) continue;

  const found = installed[path];

  if (found === undefined) {
    if (entry.optional !== true && entry.peer !== true) mismatches.push(`${path}: lock ${entry.version}, 미설치`);
  } else if (found.version !== entry.version) {
    mismatches.push(`${path}: lock ${entry.version}, 설치 ${found.version}`);
  }
}

if (mismatches.length > 0) {
  console.error(`node_modules가 package-lock.json과 다르다 (${mismatches.length}건). npm ci가 필요하다.`);
  console.error(mismatches.slice(0, 10).join("\n"));
  process.exit(1);
}

console.info("node_modules가 package-lock.json과 일치한다.");
